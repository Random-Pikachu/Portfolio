/**
 * Reads content/ and writes src/data/content.generated.ts.
 *
 * For now only the front matter of content/work/<slug>.md is used: the
 * fields a plate shows when they exist (role, hardest problem, outcomes)
 * and whether a detail sheet is published. Markdown bodies are compiled by
 * the same script once the pages that render them exist.
 *
 * Runs first in `npm run build` and as `npm run content`. The output is
 * committed so typechecking never depends on a build.
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import matter from 'gray-matter';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const WORK_DIR = join(ROOT, 'content', 'work');
const OUT = join(ROOT, 'src', 'data', 'content.generated.ts');

const str = (v) => (typeof v === 'string' ? v.trim() : '');
const list = (v) => (Array.isArray(v) ? v.map(str).filter(Boolean) : []);

const work = {};
if (existsSync(WORK_DIR)) {
  for (const file of readdirSync(WORK_DIR).sort()) {
    if (!file.endsWith('.md')) continue;
    const slug = basename(file, '.md');
    const { data } = matter(readFileSync(join(WORK_DIR, file), 'utf8'));
    work[slug] = {
      published: data.published === true,
      role: str(data.role),
      hardest: str(data.hardest),
      outcomes: list(data.outcomes),
    };
  }
}

const out = `// GENERATED by scripts/build-content.mjs from content/. Do not edit.
export interface WorkMeta {
  /** True once the detail sheet at /work/<slug> is written and built. */
  published: boolean;
  role: string;
  hardest: string;
  outcomes: string[];
}

export const WORK: Record<string, WorkMeta> = ${JSON.stringify(work, null, 2)};
`;
writeFileSync(OUT, out);
console.log(`✓ content: ${Object.keys(work).length} work entries → src/data/content.generated.ts`);
